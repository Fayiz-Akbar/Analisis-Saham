// Eksekusi seed ke tabel stock_fundamentals
export async function seedAllFundamentals() {
  console.log("🌱 Menjalankan Seeding Fundamental IDX80...");
  const stocks = await prisma.stock.findMany();

  // Buat lookup map dari list manual
  const mapManual = new Map();
  for (const item of IDX80_FUNDAMENTALS) {
    mapManual.set(item.symbol, item);
  }

  let count = 0;
  for (const s of stocks) {
    const data = mapManual.get(s.symbol) || generateStockFundamental(s.symbol, s.sector, s.industry);

    await prisma.stockFundamental.upsert({
      where: { symbol: s.symbol },
      update: {
        marketCap: data.marketCap,
        peRatio: data.peRatio,
        pbvRatio: data.pbvRatio,
        roe: data.roe,
        roa: data.roa,
        der: data.der,
        netProfitMargin: data.netProfitMargin,
        eps: data.eps,
        dividendYield: data.dividendYield,
        revenue: data.revenue,
        netIncome: data.netIncome,
        totalAssets: data.totalAssets,
        totalEquity: data.totalEquity,
        totalLiabilities: data.totalLiabilities,
        cashEquivalents: data.cashEquivalents,
        revenueGrowth: data.revenueGrowth,
        netIncomeGrowth: data.netIncomeGrowth,
        financialPeriod: data.financialPeriod,
      },
      create: {
        symbol: s.symbol,
        marketCap: data.marketCap,
        peRatio: data.peRatio,
        pbvRatio: data.pbvRatio,
        roe: data.roe,
        roa: data.roa,
        der: data.der,
        netProfitMargin: data.netProfitMargin,
        eps: data.eps,
        dividendYield: data.dividendYield,
        revenue: data.revenue,
        netIncome: data.netIncome,
        totalAssets: data.totalAssets,
        totalEquity: data.totalEquity,
        totalLiabilities: data.totalLiabilities,
        cashEquivalents: data.cashEquivalents,
        revenueGrowth: data.revenueGrowth,
        netIncomeGrowth: data.netIncomeGrowth,
        financialPeriod: data.financialPeriod,
      },
    });
    count++;
  }

  console.log(`✅ Berhasil menyimpan ${count} data fundamental saham ke PostgreSQL!`);
}

// Jika dijalankan langsung via node
if (process.argv[1]?.endsWith("seedFundamentals.js")) {
  seedAllFundamentals()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error("Error seeding fundamentals:", err);
      process.exit(1);
    });
}
